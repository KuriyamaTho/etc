n = int(input("Введите натуральное число: "))
mx = 0
mn = 9
while n > 0:
    d = n % 10
    if d > mx:
        mx = d
    if d < mn:
        mn = d
    n = n // 10
print("а) Максимальная цифра:", mx, "Минимальная цифра:", mn)
print("б) Максимальная цифра превышает минимальную на:", mx - mn)
print("в) Сумма максимальной и минимальной цифр:", mx + mn)
