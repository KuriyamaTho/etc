n = int(input("Введите натуральное число: "))

# а)
m = n
while m % 3 == 0:
    m = m // 3
if m == 1:
    print("а) Да, число является степенью числа 3")
else:
    print("а) Нет, число не является степенью числа 3")

# б)
m = n
while m % 5 == 0:
    m = m // 5
if m == 1:
    print("б) Да, число является степенью числа 5")
else:
    print("б) Нет, число не является степенью числа 5")
