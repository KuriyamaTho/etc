n = int(input("Введите количество учеников в списке: "))
prev = float(input("Введите рост ученика 1: "))
i = 1
ok = True
while i < n and ok:
    h = float(input(f"Введите рост ученика {i + 1}: "))
    i = i + 1
    ok = h < prev
    prev = h
if ok:
    print("Да, ученики перечислены в порядке убывания роста")
else:
    print("Нет, ученики перечислены не в порядке убывания роста")
