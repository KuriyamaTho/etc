n = int(input("Введите трехзначное число: "))
d1 = n // 100
d2 = n // 10 % 10
d3 = n % 10

# а)
if d1 == 4 or d1 == 7 or d2 == 4 or d2 == 7 or d3 == 4 or d3 == 7:
    print("а) Да, в число входит цифра 4 или 7")
else:
    print("а) Нет, цифры 4 и 7 в число не входят")

# б)
if d1 == 3 or d1 == 6 or d1 == 9 or d2 == 3 or d2 == 6 or d2 == 9 or d3 == 3 or d3 == 6 or d3 == 9:
    print("б) Да, в число входит цифра 3, 6 или 9")
else:
    print("б) Нет, цифры 3, 6 и 9 в число не входят")
