pop = float(input("Введите численность населения государства 1, млн: "))
area = float(input("Введите площадь государства 1, тыс. км2: "))
mn = pop / area * 1000
for i in range(2, 29):
    pop = float(input(f"Введите численность населения государства {i}, млн: "))
    area = float(input(f"Введите площадь государства {i}, тыс. км2: "))
    if pop / area * 1000 < mn:
        mn = pop / area * 1000
print("Минимальная плотность населения, чел./км2:", mn)
