k = int(input("Введите номер дня года k (1 <= k <= 365): "))

# а)
n = (k - 1) % 7
if n == 5:
    print("а) Суббота")
elif n == 6:
    print("а) Воскресенье")
else:
    print("а) Рабочий день")

# б)
d = int(input("б) Введите номер дня недели d, на который приходится 1 января (1-7): "))
n = (k - 1 + d - 1) % 7
if n == 5:
    print("б) Суббота")
elif n == 6:
    print("б) Воскресенье")
else:
    print("б) Рабочий день")
