n = int(input("Введите количество команд в списке: "))
prev = float(input("Введите количество очков команды 1: "))
i = 1
ok = True
while i < n and ok:
    p = float(input(f"Введите количество очков команды {i + 1}: "))
    i = i + 1
    ok = p <= prev
    prev = p
if ok:
    print("Да, команды перечислены в соответствии с занятыми местами")
else:
    print("Нет, команды перечислены не в соответствии с занятыми местами")
