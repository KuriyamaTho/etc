n = int(input("Введите количество людей в группе: "))
s1 = 0
k1 = 0
s2 = 0
k2 = 0
for i in range(1, n + 1):
    m = float(input(f"Введите массу человека {i}, кг: "))
    if m > 100:
        s1 = s1 + m
        k1 = k1 + 1
    else:
        s2 = s2 + m
        k2 = k2 + 1
print("Средняя масса полных людей:", s1 / k1)
if k2 > 0:
    print("Средняя масса остальных людей:", s2 / k2)
else:
    print("Остальных людей в группе нет")
