n = float(input("Введите число n: "))
f = float(input("Введите первый член прогрессии f: "))
s = float(input("Введите шаг прогрессии s: "))
t = f
if s > 0:
    while t < n - 1e-9:
        t = t + s
elif s < 0:
    while t > n + 1e-9:
        t = t + s
if abs(t - n) < 1e-9:
    print("Да, число является членом арифметической прогрессии")
else:
    print("Нет, число не является членом арифметической прогрессии")
