n = int(input("Введите натуральное число n (n <= 9999): "))
d1 = n // 1000
d2 = n // 100 % 10
d3 = n // 10 % 10
d4 = n % 10
if ((d1 == d2 and d2 == d3 and d3 != d4)
        or (d1 == d2 and d2 == d4 and d4 != d3)
        or (d1 == d3 and d3 == d4 and d4 != d2)
        or (d2 == d3 and d3 == d4 and d4 != d1)):
    print("Да, число содержит ровно три одинаковые цифры")
else:
    print("Нет, число не содержит ровно три одинаковые цифры")
