n = int(input("Введите трехзначное число: "))
d1 = n // 100
d2 = n // 10 % 10
d3 = n % 10

# а)
if d1 > d3:
    print("а) Больше первая цифра")
elif d1 < d3:
    print("а) Больше последняя цифра")
else:
    print("а) Цифры равны")

# б)
if d1 > d2:
    print("б) Больше первая цифра")
elif d1 < d2:
    print("б) Больше вторая цифра")
else:
    print("б) Цифры равны")

# в)
if d2 > d3:
    print("в) Больше вторая цифра")
elif d2 < d3:
    print("в) Больше последняя цифра")
else:
    print("в) Цифры равны")
