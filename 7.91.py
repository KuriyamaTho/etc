n = int(input("Введите количество грузов n: "))
cap = float(input("Введите грузоподъемность автомобиля: "))
s = 0
for i in range(1, n + 1):
    m = float(input(f"Введите массу груза {i}: "))
    s = s + m
if s > cap:
    print("Общая масса грузов превысила грузоподъемность автомобиля")
else:
    print("Общая масса грузов не превысила грузоподъемность автомобиля")
