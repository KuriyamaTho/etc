k = 0
prev = int(input("Введите число (0 - конец последовательности): "))
x = int(input("Введите число (0 - конец последовательности): "))
while x != 0:
    if prev * x < 0:
        k = k + 1
    prev = x
    x = int(input("Введите число (0 - конец последовательности): "))
print("Знак меняется раз:", k)
