n = int(input("Введите количество учеников в классе: "))
sb = 0
kb = 0
sg = 0
kg = 0
for i in range(1, n + 1):
    h = float(input(f"Введите рост ученика {i} (у мальчиков со знаком минус), см: "))
    if h < 0:
        sb = sb - h
        kb = kb + 1
    else:
        sg = sg + h
        kg = kg + 1
if sb / kb - sg / kg > 10:
    print("Да, средний рост мальчиков превышает средний рост девочек более чем на 10 см")
else:
    print("Нет, средний рост мальчиков превышает средний рост девочек не более чем на 10 см")
