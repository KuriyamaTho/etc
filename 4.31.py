n = int(input("Введите трехзначное число: "))
d1 = n // 100
d2 = n // 10 % 10
d3 = n % 10

# а)
if d1 == d2 and d2 == d3:
    print("а) Да, все цифры одинаковые")
else:
    print("а) Нет, не все цифры одинаковые")

# б)
if d1 == d2 or d1 == d3 or d2 == d3:
    print("б) Да, среди цифр есть одинаковые")
else:
    print("б) Нет, среди цифр нет одинаковых")
