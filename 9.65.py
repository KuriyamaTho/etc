s = input("Введите предложение: ")

# а)
k = 0
for i in range(len(s) - 1):
    if s[i] == "р" and s[i + 1] == "о":
        k = k + 1
print("а) Число вхождений буквосочетания ро:", k)

# б)
c1 = input("б) Введите первую букву сочетания: ")
c2 = input("б) Введите вторую букву сочетания: ")
k = 0
for i in range(len(s) - 1):
    if s[i] == c1 and s[i + 1] == c2:
        k = k + 1
print("б) Число вхождений буквосочетания:", k)

# в)
t = input("в) Введите буквосочетание: ")
k = 0
for i in range(len(s) - len(t) + 1):
    if s[i:i + len(t)] == t:
        k = k + 1
print("в) Число вхождений буквосочетания:", k)
