n = int(input("Введите количество квартир n: "))
a = int(input("Введите номер первой квартиры a: "))
odd = n // 2
if n % 2 == 1 and a % 2 == 1:
    odd = odd + 1
if odd % 2 == 0:
    print("Да, сумма номеров всех квартир является четным числом")
else:
    print("Нет, сумма номеров всех квартир является нечетным числом")
