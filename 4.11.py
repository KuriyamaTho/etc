v1 = float(input("Введите объем первого тела: "))
m1 = float(input("Введите массу первого тела: "))
v2 = float(input("Введите объем второго тела: "))
m2 = float(input("Введите массу второго тела: "))
if m1 / v1 > m2 / v2:
    print("Большую плотность имеет материал первого тела")
elif m1 / v1 < m2 / v2:
    print("Большую плотность имеет материал второго тела")
else:
    print("Плотности материалов равны")
