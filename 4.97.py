a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
c = int(input("Введите третье число: "))

# а)
if a > b and a > c:
    print("а) Самое большое - первое число")
elif b > a and b > c:
    print("а) Самое большое - второе число")
else:
    print("а) Самое большое - третье число")

# б)
if a < b and a < c:
    print("б) Самое маленькое - первое число")
elif b < a and b < c:
    print("б) Самое маленькое - второе число")
else:
    print("б) Самое маленькое - третье число")

# в)
if (a > b and a < c) or (a < b and a > c):
    print("в) Средним является первое число")
elif (b > a and b < c) or (b < a and b > c):
    print("в) Средним является второе число")
else:
    print("в) Средним является третье число")
