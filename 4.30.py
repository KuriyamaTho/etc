n = int(input("Введите трехзначное число: "))
a = int(input("Введите число a: "))
d1 = n // 100
d2 = n // 10 % 10
d3 = n % 10
s = d1 + d2 + d3
p = d1 * d2 * d3

# а)
if s >= 10:
    print("а) Да, сумма цифр является двузначным числом")
else:
    print("а) Нет, сумма цифр не является двузначным числом")

# б)
if 100 <= p <= 999:
    print("б) Да, произведение цифр является трехзначным числом")
else:
    print("б) Нет, произведение цифр не является трехзначным числом")

# в)
if p > a:
    print("в) Да, произведение цифр больше числа a")
else:
    print("в) Нет, произведение цифр не больше числа a")

# г)
if s % 5 == 0:
    print("г) Да, сумма цифр кратна пяти")
else:
    print("г) Нет, сумма цифр не кратна пяти")

# д)
if s % a == 0:
    print("д) Да, сумма цифр кратна числу a")
else:
    print("д) Нет, сумма цифр не кратна числу a")
