first = int(input("Введите число (отрицательное - конец последовательности): "))
x = int(input("Введите число (отрицательное - конец последовательности): "))
same = True
while x >= 0 and same:
    same = x == first
    if same:
        x = int(input("Введите число (отрицательное - конец последовательности): "))
if same:
    print("Да, все элементы равны между собой")
else:
    print("Нет, не все элементы равны между собой")
