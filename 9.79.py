s = input("1) Введите текст, в котором есть точка: ")
i = 0
k = 0
while s[i] != ".":
    if s[i] == "и":
        k = k + 1
    i = i + 1
print("1) Количество букв и в первом предложении:", k)

# 2)
s = input("2) Введите текст (точки может не быть): ")
i = 0
k = 0
while i < len(s) and s[i] != ".":
    if s[i] == "и":
        k = k + 1
    i = i + 1
print("2) Количество букв и в первом предложении:", k)
