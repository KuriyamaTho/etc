n = int(input("Введите четырехзначное число: "))
a = n // 1000
b = n // 100 % 10
c = n // 10 % 10
d = n % 10

# а)
print("а)", d * 1000 + c * 100 + b * 10 + a)

# б)
print("б)", b * 1000 + a * 100 + d * 10 + c)

# в)
print("в)", a * 1000 + c * 100 + b * 10 + d)

# г)
print("г) 1) с выделением цифр:", c * 1000 + d * 100 + a * 10 + b)
print("г) 2) без выделения цифр:", n % 100 * 100 + n // 100)
