n = int(input("Введите количество команд: "))
p = int(input("Введите количество очков команды 1: "))
mn = p
pos = 1
for i in range(2, n + 1):
    p = int(input(f"Введите количество очков команды {i}: "))
    if p < mn:
        mn = p
        pos = i
print("Наименьшее количество очков набрала команда:", pos)
