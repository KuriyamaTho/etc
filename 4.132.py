a = int(input("Поезд прибывает, часы a: "))
b = int(input("Поезд прибывает, минуты b: "))
c = int(input("Поезд отправляется, часы c: "))
d = int(input("Поезд отправляется, минуты d: "))
n = int(input("Пассажир пришел, часы n: "))
m = int(input("Пассажир пришел, минуты m: "))
arrive = a * 60 + b
leave = c * 60 + d
come = n * 60 + m
if arrive <= come <= leave:
    print("Да, поезд будет стоять на платформе")
else:
    print("Нет, поезда на платформе не будет")
