s = input("1) Введите предложение без начальных и конечных пробелов: ")
k = 1
for i in range(len(s) - 1):
    if s[i] == " " and s[i + 1] != " ":
        k = k + 1
print("1) Количество слов:", k)

# 2)
s = input("2) Введите предложение (возможны начальные и конечные пробелы): ")
k = 0
for i in range(len(s)):
    if s[i] != " " and (i == 0 or s[i - 1] == " "):
        k = k + 1
print("2) Количество слов:", k)
