x1 = float(input("Первый прямоугольник, левый нижний угол, x: "))
y1 = float(input("Первый прямоугольник, левый нижний угол, y: "))
w1 = float(input("Первый прямоугольник, длина стороны по x: "))
h1 = float(input("Первый прямоугольник, длина стороны по y: "))
x2 = float(input("Второй прямоугольник, левый нижний угол, x: "))
y2 = float(input("Второй прямоугольник, левый нижний угол, y: "))
w2 = float(input("Второй прямоугольник, длина стороны по x: "))
h2 = float(input("Второй прямоугольник, длина стороны по y: "))

first_in_second = x1 >= x2 and y1 >= y2 and x1 + w1 <= x2 + w2 and y1 + h1 <= y2 + h2
second_in_first = x2 >= x1 and y2 >= y1 and x2 + w2 <= x1 + w1 and y2 + h2 <= y1 + h1

# а)
if first_in_second:
    print("а) Да, все точки первого прямоугольника принадлежат второму")
else:
    print("а) Нет, не все точки первого прямоугольника принадлежат второму")

# б)
if first_in_second or second_in_first:
    print("б) Да, все точки одного из прямоугольников принадлежат другому")
else:
    print("б) Нет, ни один прямоугольник не лежит целиком в другом")

# в)
if x1 <= x2 + w2 and x2 <= x1 + w1 and y1 <= y2 + h2 and y2 <= y1 + h1:
    print("в) Да, прямоугольники пересекаются")
else:
    print("в) Нет, прямоугольники не пересекаются")
