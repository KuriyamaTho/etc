n = int(input("Введите натуральное число n: "))
s1 = 0
s2 = 0
for i in range(1, n + 1):
    a = int(input(f"Введите a{i}: "))
    if a < 20.5:
        s1 = s1 + a
    if a <= 10:
        s2 = s2 + a
if s1 <= 50:
    print("а) Да, сумма чисел, меньших 20,5, не превышает 50")
else:
    print("а) Нет, сумма чисел, меньших 20,5, превышает 50")
if s2 % 3 == 0:
    print("б) Да, сумма чисел, не превышающих 10, кратна трем")
else:
    print("б) Нет, сумма чисел, не превышающих 10, не кратна трем")
