k = int(input("Введите число учеников в классе 1: "))
mx = k
mn = k
for i in range(2, 21):
    k = int(input(f"Введите число учеников в классе {i}: "))
    if k > mx:
        mx = k
    if k < mn:
        mn = k
print("Численность самого большого класса превышает численность самого маленького на:", mx - mn)
