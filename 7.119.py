n = int(input("Введите натуральное число n: "))
a = int(input("Введите a1: "))
mx = a
mn = a
for i in range(2, n + 1):
    a = int(input(f"Введите a{i}: "))
    if a > mx:
        mx = a
    if a < mn:
        mn = a
if mx - mn <= 25:
    print("Да, максимальное число превышает минимальное не более чем на 25")
else:
    print("Нет, максимальное число превышает минимальное более чем на 25")
