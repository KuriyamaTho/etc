n = int(input("Введите натуральное число: "))
last = n % 10
k = 0
s = 0
p = 1
s2 = 0
s3 = 0
while n > 0:
    d = n % 10
    k = k + 1
    s = s + d
    p = p * d
    s2 = s2 + d * d
    s3 = s3 + d * d * d
    first = d
    n = n // 10
print("а) Количество цифр:", k)
print("б) Сумма цифр:", s)
print("в) Произведение цифр:", p)
print("г) Среднее арифметическое цифр:", s / k)
print("д) Сумма квадратов цифр:", s2)
print("е) Сумма кубов цифр:", s3)
print("ж) Первая цифра:", first)
print("з) Сумма первой и последней цифр:", first + last)
