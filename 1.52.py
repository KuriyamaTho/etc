a = float(input("Стоимость 1 кг конфет: "))
b = float(input("Стоимость 1 кг печенья: "))
c = float(input("Стоимость 1 кг яблок: "))
x = float(input("Куплено конфет, кг: "))
y = float(input("Куплено печенья, кг: "))
z = float(input("Куплено яблок, кг: "))
cost = a * x + b * y + c * z
print("Стоимость покупки =", cost)
