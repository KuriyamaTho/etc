n = int(input("Введите натуральное число: "))
prev = n % 10
n = n // 10
ok = True
while n > 0 and ok:
    d = n % 10
    ok = d <= prev
    prev = d
    n = n // 10
if ok:
    print("Да, цифры слева направо упорядочены по неубыванию")
else:
    print("Нет, цифры слева направо не упорядочены по неубыванию")
