a = float(input("Введите первое число: "))
b = float(input("Введите второе число (отличное от первого): "))

# а)
if a > b:
    mx = a
    mn = b
if a < b:
    mx = b
    mn = a
print("а) Наибольшее число:", mx, "Наименьшее число:", mn)

