# 1) в какие-то дни мая осадки выпадали
k = 0
x = float(input("1) Введите количество осадков за 1 мая: "))
while x == 0:
    k = k + 1
    x = float(input(f"1) Введите количество осадков за {k + 1} мая: "))
print("1) Осадков не было первые дни подряд:", k)

# 2) осадков могло не быть ни в какой день мая
k = 0
i = 0
dry = True
while i < 31 and dry:
    x = float(input(f"2) Введите количество осадков за {i + 1} мая: "))
    i = i + 1
    dry = x == 0
    k = k + dry
print("2) Осадков не было первые дни подряд:", k)
