a = int(input("Введите длину стола a: "))
b = int(input("Введите ширину стола b (a > b): "))
c = int(input("Введите длину прямоугольника c: "))
d = int(input("Введите ширину прямоугольника d (c > d): "))
n1 = (a // c) * (b // d)
n2 = (b // c) * (a // d)
print("Вдоль длинной стороны стола помещается:", n1)
print("Вдоль короткой стороны стола помещается:", n2)
if n1 > n2:
    print("Больше прямоугольников разместится длинной стороной вдоль длинной стороны стола")
elif n1 < n2:
    print("Больше прямоугольников разместится длинной стороной вдоль короткой стороны стола")
else:
    print("Оба способа дают одинаковое количество прямоугольников")
