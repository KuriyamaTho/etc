a = float(input("Введите a: "))
b = float(input("Введите b: "))
c = float(input("Введите c: "))

# а)
if a < b < c:
    print("а) Да, неравенство a < b < c выполняется")
else:
    print("а) Нет, неравенство a < b < c не выполняется")

# б)
if b > a > c:
    print("б) Да, неравенство b > a > c выполняется")
else:
    print("б) Нет, неравенство b > a > c не выполняется")
