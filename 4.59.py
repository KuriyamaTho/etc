n = int(input("Введите четырехзначное число: "))
b = int(input("Введите цифру b: "))
d1 = n // 1000
d2 = n // 100 % 10
d3 = n // 10 % 10
d4 = n % 10

# а)
if d1 == 4 or d2 == 4 or d3 == 4 or d4 == 4:
    print("а) Да, цифра 4 входит в число")
else:
    print("а) Нет, цифра 4 не входит в число")

# б)
if d1 == b or d2 == b or d3 == b or d4 == b:
    print("б) Да, цифра b входит в число")
else:
    print("б) Нет, цифра b не входит в число")
