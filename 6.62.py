n = int(input("Введите число n: "))
i = 1
x = int(input("Введите число (10000 - конец последовательности): "))
while x != 10000 and x <= n:
    i = i + 1
    x = int(input("Введите число (10000 - конец последовательности): "))
if x != 10000:
    print("Номер первого числа, большего n:", i)
else:
    print("Чисел, больших n, в последовательности нет")
