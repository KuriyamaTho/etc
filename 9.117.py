s = input("Введите строку: ")
t = ""
for ch in s:
    if ch != " ":
        t = t + ch
i = 0
j = len(t) - 1
while i < j and t[i] == t[j]:
    i = i + 1
    j = j - 1
if i >= j:
    print("Да, строка после удаления пробелов является перевертышем")
else:
    print("Нет, строка после удаления пробелов не является перевертышем")
