n = int(input("Введите количество людей в группе: "))
m = float(input("Введите массу человека 1: "))
mx = m
mn = m
for i in range(2, n + 1):
    m = float(input(f"Введите массу человека {i}: "))
    if m > mx:
        mx = m
    if m < mn:
        mn = m
if mx > 2 * mn:
    print("Да, масса самого тяжелого более чем в 2 раза превышает массу самого легкого")
else:
    print("Нет, масса самого тяжелого не более чем в 2 раза превышает массу самого легкого")
