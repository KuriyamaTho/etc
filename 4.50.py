a = float(input("Введите сторону a: "))
b = float(input("Введите сторону b: "))
c = float(input("Введите сторону c: "))
d = float(input("Введите сторону d: "))
if (a <= c and b <= d) or (a <= d and b <= c):
    print("Да, прямоугольник со сторонами a, b можно уместить внутри прямоугольника со сторонами c, d")
else:
    print("Нет, прямоугольник со сторонами a, b нельзя уместить внутри прямоугольника со сторонами c, d")
