n = int(input("Введите натуральное число: "))
a = int(input("Введите число a: "))
mx = 0
mn = 9
while n > 0:
    d = n % 10
    if d > mx:
        mx = d
    if d < mn:
        mn = d
    n = n // 10
if (mx + mn) % a == 0:
    print("Да, сумма максимальной и минимальной цифр кратна a")
else:
    print("Нет, сумма максимальной и минимальной цифр не кратна a")
