n = int(input("Введите трехзначное число: "))
k = int(input("Введите цифру n: "))
d1 = n // 100
d2 = n // 10 % 10
d3 = n % 10

# а)
if d1 == 6 or d2 == 6 or d3 == 6:
    print("а) Да, цифра 6 входит в число")
else:
    print("а) Нет, цифра 6 не входит в число")

# б)
if d1 == k or d2 == k or d3 == k:
    print("б) Да, цифра n входит в число")
else:
    print("б) Нет, цифра n не входит в число")
