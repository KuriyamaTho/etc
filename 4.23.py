n = int(input("Введите двузначное число: "))
d1 = n // 10
d2 = n % 10

# а)
if d1 > d2:
    print("а) Больше первая цифра")
elif d1 < d2:
    print("а) Больше вторая цифра")
else:
    print("а) Цифры равны")

# б)
if d1 == d2:
    print("б) Да, цифры одинаковы")
else:
    print("б) Нет, цифры разные")
