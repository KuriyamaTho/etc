# а)
a = 0.0
b = 1.0
while b - a > 0.001:
    c = (a + b) / 2
    fa = a ** 4 + 2 * a ** 3 - a - 1
    fc = c ** 4 + 2 * c ** 3 - c - 1
    if fa * fc <= 0:
        b = c
    else:
        a = c
print("а) Корень уравнения (приближенно):", (a + b) / 2)

