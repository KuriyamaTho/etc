a = 1.0
b = 1.5
while b - a > 0.001:
    c = (a + b) / 2
    fa = a ** 3 - 0.2 * a ** 2 - 0.2 * a - 1.2
    fc = c ** 3 - 0.2 * c ** 2 - 0.2 * c - 1.2
    if fa * fc <= 0:
        b = c
    else:
        a = c
print("б) Корень уравнения (приближенно):", (a + b) / 2)
