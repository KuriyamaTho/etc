# 1) пятерки имеют не все ученики
k = 0
x = int(input("1) Введите оценку ученика 1: "))
while x == 5:
    k = k + 1
    x = int(input(f"1) Введите оценку ученика {k + 1}: "))
print("1) Количество учеников с оценкой 5:", k)

# 2) пятерки могут иметь все ученики
k = 0
i = 0
five = True
while i < 20 and five:
    x = int(input(f"2) Введите оценку ученика {i + 1}: "))
    i = i + 1
    five = x == 5
    k = k + five
print("2) Количество учеников с оценкой 5:", k)
