n = int(input("Введите натуральное число: "))

# а)
if n % 2 == 0:
    print("а) Да, число заканчивается четной цифрой")
else:
    print("а) Нет, число не заканчивается четной цифрой")

# б)
if n % 2 == 1:
    print("б) Да, число заканчивается нечетной цифрой")
else:
    print("б) Нет, число не заканчивается нечетной цифрой")
