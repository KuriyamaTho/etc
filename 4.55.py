n = int(input("Введите двузначное число: "))
a = int(input("Введите цифру a: "))
d1 = n // 10
d2 = n % 10

# а)
if d1 == 3 or d2 == 3:
    print("а) Да, цифра 3 входит в число")
else:
    print("а) Нет, цифра 3 не входит в число")

# б)
if d1 == a or d2 == a:
    print("б) Да, цифра a входит в число")
else:
    print("б) Нет, цифра a не входит в число")
