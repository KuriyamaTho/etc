n = int(input("Введите количество дней в феврале (28 или 29): "))
last = float(input("Введите общее количество осадков за февраль прошлого года: "))
s = 0
for i in range(1, n + 1):
    x = float(input(f"Введите количество осадков за {i} февраля: "))
    s = s + x
if s > last:
    print("Да, количество осадков превысило прошлогоднее")
else:
    print("Нет, количество осадков не превысило прошлогоднее")
