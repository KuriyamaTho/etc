n = int(input("Введите количество троек: "))
k = 0
for i in range(1, n + 1):
    a = int(input(f"Тройка {i}, число a: "))
    b = int(input(f"Тройка {i}, число b (a <= b): "))
    c = int(input(f"Тройка {i}, число c (b <= c): "))
    if a + b > c:
        k = k + 1
print("Количество троек, из которых можно построить треугольник:", k)
