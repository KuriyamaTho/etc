pos = 0
prev = float(input("Введите число (10000 - конец последовательности): "))
x = float(input("Введите число (10000 - конец последовательности): "))
i = 2
while x != 10000 and pos == 0:
    if x <= prev:
        pos = i
    prev = x
    i = i + 1
    if pos == 0:
        x = float(input("Введите число (10000 - конец последовательности): "))
if pos == 0:
    print("Да, последовательность упорядочена по возрастанию")
else:
    print("Нет, первое число, нарушающее упорядоченность, имеет номер", pos)
