h = int(input("Введите h (0 < h <= 12): "))
m = int(input("Введите m (0 <= m <= 59): "))
d = (11 * m - 60 * (h % 12)) % 720
print("а) Стрелки совпадут через (полных минут):", (720 - d) % 720 // 11)
print("б) Стрелки будут перпендикулярны через (полных минут):", min((180 - d) % 720, (540 - d) % 720) // 11)
