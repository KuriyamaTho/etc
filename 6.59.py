pos = 0
i = 1
x = int(input("Введите число (100 - конец последовательности): "))
while x != 100 and pos == 0:
    if x == 77:
        pos = i
    i = i + 1
    if pos == 0:
        x = int(input("Введите число (100 - конец последовательности): "))
if pos > 0:
    print("Да, число 77 есть в последовательности, его номер:", pos)
else:
    print("Нет, числа 77 в последовательности нет")
