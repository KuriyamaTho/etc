s = input("1) Введите последовательность, в которой не все символы одинаковые: ")
i = 0
while s[i] == s[0]:
    i = i + 1
print("1) Количество одинаковых символов в начале:", i)

# 2)
s = input("2) Введите последовательность (все символы могут быть одинаковыми): ")
i = 0
while i < len(s) and s[i] == s[0]:
    i = i + 1
print("2) Количество одинаковых символов в начале:", i)
