n = int(input("Введите натуральное число n: "))
x = int(input("Введите x: "))
k = 0
for i in range(1, n + 1):
    a = int(input(f"Введите a{i}: "))
    if a < 0:
        k = k + 1
if k > x:
    print("Да, количество отрицательных чисел превышает x")
else:
    print("Нет, количество отрицательных чисел не превышает x")
