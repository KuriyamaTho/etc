print("а) Двузначные числа, сумма квадратов цифр которых делится на 13:")
for x in range(10, 100):
    if ((x // 10) ** 2 + (x % 10) ** 2) % 13 == 0:
        print(x)

# б)
print("б) Двузначные числа, равные сумме цифр, сложенной с ее квадратом:")
for x in range(10, 100):
    s = x // 10 + x % 10
    if s + s ** 2 == x:
        print(x)
