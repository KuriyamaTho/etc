n = int(input("Введите натуральное число: "))

# а)
m = n
r = 0
while m > 0:
    r = r * 10 + m % 10
    m = m // 10
print("а) Цифры справа налево:", r)

# длина числа и степень десяти
m = n
p = 1
while m >= 10:
    p = p * 10
    m = m // 10
# p = 10 в степени (количество цифр - 1)

# б)
print("б) С двойками в начале и в конце:", 2 * p * 100 + n * 10 + 2)

# в)
a = int(input("в) Введите цифру a: "))
m = n
r = 0
mult = 1
while m > 0:
    d = m % 10
    if d != a:
        r = r + d * mult
        mult = mult * 10
    m = m // 10
print("в) После удаления цифр a:", r)

# г)
first = n // p
last = n % 10
print("г) После перестановки первой и последней цифр:", last * p + (n - first * p - last) + first)

# д)
print("д) Число, приписанное к самому себе:", n * p * 10 + n)
