a = float(input("Введите размер форточки a, см: "))
b = float(input("Введите размер форточки b, см: "))
d = float(input("Введите диаметр головы d, см: "))
if d + 2 <= a and d + 2 <= b:
    print("Да, Вася сможет высунуть голову в форточку")
else:
    print("Нет, Вася не сможет высунуть голову в форточку")
