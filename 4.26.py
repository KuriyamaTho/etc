n = int(input("Введите двузначное число: "))
a = int(input("Введите число a: "))
s = n // 10 + n % 10

# а)
if s % 3 == 0:
    print("а) Да, сумма цифр кратна трем")
else:
    print("а) Нет, сумма цифр не кратна трем")

# б)
if s % a == 0:
    print("б) Да, сумма цифр кратна числу a")
else:
    print("б) Нет, сумма цифр не кратна числу a")
