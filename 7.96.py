s1 = 0
s2 = 0
for i in range(1, 11):
    b = int(input(f"Введите b{i}: "))
    if b > 20:
        s1 = s1 + b
    if b < 50:
        s2 = s2 + b
if s1 > 100:
    print("а) Да, сумма чисел, больших 20, превышает 100")
else:
    print("а) Нет, сумма чисел, больших 20, не превышает 100")
if s2 % 2 == 0:
    print("б) Да, сумма чисел, меньших 50, четная")
else:
    print("б) Нет, сумма чисел, меньших 50, нечетная")
