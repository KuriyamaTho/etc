s = input("1) Введите предложение, в котором есть запятые: ")
i = 0
k = 0
while s[i] != ",":
    if s[i] == "н":
        k = k + 1
    i = i + 1
print("1) Количество букв н до первой запятой:", k)

# 2)
s = input("2) Введите предложение (запятых может не быть): ")
i = 0
k = 0
while i < len(s) and s[i] != ",":
    if s[i] == "н":
        k = k + 1
    i = i + 1
print("2) Количество букв н до первой запятой:", k)
