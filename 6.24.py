x0 = int(input("Введите число x: "))
s = 0
k = 0
x = int(input("Введите число последовательности (0 - конец): "))
while x != 0:
    if x > x0:
        s = s + x
    if x % 2 == 0:
        k = k + 1
    x = int(input("Введите число последовательности (0 - конец): "))
print("а) Сумма чисел, больших x:", s)
print("б) Количество четных чисел:", k)
