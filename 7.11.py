print("а) Трехзначные числа, чьи квадраты оканчиваются этими же тремя цифрами:")
for x in range(100, 1000):
    if x * x % 1000 == x:
        print(x)

# б)
print("б) Трехзначные числа, кратные семи, с суммой цифр, кратной семи:")
for x in range(100, 1000):
    if x % 7 == 0 and (x // 100 + x // 10 % 10 + x % 10) % 7 == 0:
        print(x)
