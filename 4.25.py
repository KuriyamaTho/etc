n = int(input("Введите двузначное число: "))
a = int(input("Введите число a: "))
s = n // 10 + n % 10

# а)
if s >= 10:
    print("а) Да, сумма цифр является двузначным числом")
else:
    print("а) Нет, сумма цифр не является двузначным числом")

# б)
if s > a:
    print("б) Да, сумма цифр больше числа a")
else:
    print("б) Нет, сумма цифр не больше числа a")
