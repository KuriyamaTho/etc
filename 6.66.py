pos = 0
prev = int(input("Введите число (-1 - конец последовательности): "))
x = int(input("Введите число (-1 - конец последовательности): "))
i = 2
while x != -1 and pos == 0:
    if x == prev:
        pos = i - 1
    prev = x
    i = i + 1
    if pos == 0:
        x = int(input("Введите число (-1 - конец последовательности): "))
if pos > 0:
    print("Да, первая пара одинаковых соседних чисел:", pos, "и", pos + 1)
else:
    print("Нет, одинаковых соседних чисел нет")
