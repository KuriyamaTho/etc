km = float(input("Введите расстояние в километрах: "))
ft = float(input("Введите расстояние в футах: "))
if km * 1000 < ft * 0.305:
    print("Меньше расстояние, заданное в километрах")
elif km * 1000 > ft * 0.305:
    print("Меньше расстояние, заданное в футах")
else:
    print("Расстояния равны")
