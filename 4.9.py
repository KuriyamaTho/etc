v1 = float(input("Введите скорость в километрах в час: "))
v2 = float(input("Введите скорость в метрах в секунду: "))
if v1 / 3.6 > v2:
    print("Больше скорость, заданная в километрах в час")
elif v1 / 3.6 < v2:
    print("Больше скорость, заданная в метрах в секунду")
else:
    print("Скорости равны")
