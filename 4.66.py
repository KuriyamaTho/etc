a = int(input("Введите длину стола a: "))
b = int(input("Введите ширину стола b (a > b): "))
c = int(input("Введите размер кости c: "))
d = int(input("Введите размер кости d (c > d): "))
e = int(input("Введите размер кости e (d > e): "))

n1 = (a // c) * (b // d)
n2 = (a // d) * (b // c)
n3 = (a // c) * (b // e)
n4 = (a // e) * (b // c)
n5 = (a // d) * (b // e)
n6 = (a // e) * (b // d)

best = n1
if n2 > best:
    best = n2
if n3 > best:
    best = n3
if n4 > best:
    best = n4
if n5 > best:
    best = n5
if n6 > best:
    best = n6

print("Наибольшее количество костей:", best)
if best == n1:
    print("Вариант: кость лежит гранью c x d, ребро c параллельно стороне a, ребро d параллельно стороне b")
elif best == n2:
    print("Вариант: кость лежит гранью c x d, ребро c параллельно стороне b, ребро d параллельно стороне a")
elif best == n3:
    print("Вариант: кость лежит гранью c x e, ребро c параллельно стороне a, ребро e параллельно стороне b")
elif best == n4:
    print("Вариант: кость лежит гранью c x e, ребро c параллельно стороне b, ребро e параллельно стороне a")
elif best == n5:
    print("Вариант: кость лежит гранью d x e, ребро d параллельно стороне a, ребро e параллельно стороне b")
else:
    print("Вариант: кость лежит гранью d x e, ребро d параллельно стороне b, ребро e параллельно стороне a")
