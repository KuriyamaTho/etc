a = float(input("Введите размер конверта a, мм: "))
b = float(input("Введите размер конверта b, мм: "))
c = float(input("Введите размер открытки c, мм: "))
d = float(input("Введите размер открытки d, мм: "))
if (c + 2 <= a and d + 2 <= b) or (c + 2 <= b and d + 2 <= a):
    print("Да, открытка войдет в конверт")
else:
    print("Нет, открытка не войдет в конверт")
