n = int(input("Введите количество дней в феврале (28 или 29): "))
even = 0
odd = 0
for i in range(1, n + 1):
    x = float(input(f"Введите количество осадков за {i} февраля: "))
    if i % 2 == 0:
        even = even + x
    else:
        odd = odd + x
if even > odd:
    print("Да, по четным числам выпало больше осадков, чем по нечетным")
else:
    print("Нет, по четным числам выпало не больше осадков, чем по нечетным")
