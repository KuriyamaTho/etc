n = int(input("Введите четырехзначное число: "))
a = int(input("Введите число a: "))
d1 = n // 1000
d2 = n // 100 % 10
d3 = n // 10 % 10
d4 = n % 10
s = d1 + d2 + d3 + d4
p = d1 * d2 * d3 * d4

# а)
if d1 + d2 == d3 + d4:
    print("а) Да, сумма двух первых цифр равна сумме двух последних")
else:
    print("а) Нет, сумма двух первых цифр не равна сумме двух последних")

# б)
if s % 3 == 0:
    print("б) Да, сумма цифр кратна трем")
else:
    print("б) Нет, сумма цифр не кратна трем")

# в)
if p % 4 == 0:
    print("в) Да, произведение цифр кратно четырем")
else:
    print("в) Нет, произведение цифр не кратно четырем")

# г)
if p % a == 0:
    print("г) Да, произведение цифр кратно числу a")
else:
    print("г) Нет, произведение цифр не кратно числу a")
