n = int(input("Введите натуральное число: "))
mx = 0
mn = 9
while n > 0:
    d = n % 10
    if d > mx:
        mx = d
    if d < mn:
        mn = d
    n = n // 10
if (mx - mn) % 2 == 0:
    print("Да, разность максимальной и минимальной цифр четная")
else:
    print("Нет, разность максимальной и минимальной цифр нечетная")
