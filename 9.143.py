s = input("Введите текст: ")
i = 0
if len(s) > 0 and (s[0] == "+" or s[0] == "-"):
    i = 1
ok = i < len(s)
while i < len(s) and ok:
    ok = "0" <= s[i] <= "9"
    i = i + 1
if ok:
    print("Да, текст является правильной десятичной записью целого числа")
else:
    print("Нет, текст не является правильной десятичной записью целого числа")
