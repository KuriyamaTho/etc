n = int(input("Введите общее количество марок автомобилей и мотоциклов: "))
sc = 0
kc = 0
sm = 0
km = 0
for i in range(1, n + 1):
    c = float(input(f"Введите стоимость марки {i}, $: "))
    if c > 5000:
        sc = sc + c
        kc = kc + 1
    else:
        sm = sm + c
        km = km + 1
if sc / kc > 3 * (sm / km):
    print("Да, средняя стоимость автомобилей более чем в 3 раза превышает среднюю стоимость мотоциклов")
else:
    print("Нет, средняя стоимость автомобилей не более чем в 3 раза превышает среднюю стоимость мотоциклов")
