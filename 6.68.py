pos = 0
prev = int(input("Введите число (9999 - конец последовательности): "))
x = int(input("Введите число (9999 - конец последовательности): "))
i = 2
while x != 9999 and pos == 0:
    if x % 2 == 0 and prev % 2 == 0:
        pos = i - 1
    prev = x
    i = i + 1
    if pos == 0:
        x = int(input("Введите число (9999 - конец последовательности): "))
if pos > 0:
    print("Да, первая пара соседних четных чисел:", pos, "и", pos + 1)
else:
    print("Нет, пар соседних четных чисел нет")
