n = int(input("Введите натуральное число: "))

# вычисления
m = n
s = 0
p = 1
k = 0
last = n % 10
while m > 0:
    d = m % 10
    s = s + d
    p = p * d
    k = k + 1
    first = d
    m = m // 10

# а)
if s > 10:
    print("а) Да, сумма цифр больше 10")
else:
    print("а) Нет, сумма цифр не больше 10")

# б)
if p < 50:
    print("б) Да, произведение цифр меньше 50")
else:
    print("б) Нет, произведение цифр не меньше 50")

# в)
if k % 2 == 0:
    print("в) Да, количество цифр четное")
else:
    print("в) Нет, количество цифр нечетное")

# г)
if k == 4:
    print("г) Да, число четырехзначное")
else:
    print("г) Нет, число не четырехзначное")

# д)
if first <= 6:
    print("д) Да, первая цифра не превышает 6")
else:
    print("д) Нет, первая цифра превышает 6")

# е)
if first == last:
    print("е) Да, число начинается и заканчивается одной и той же цифрой")
else:
    print("е) Нет, первая и последняя цифры разные")

# ж)
if first > last:
    print("ж) Больше первая цифра")
elif first < last:
    print("ж) Больше последняя цифра")
else:
    print("ж) Первая и последняя цифры равны")
