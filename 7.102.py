n = int(input("Введите количество домов на улице: "))
even = 0
odd = 0
for i in range(1, n + 1):
    k = int(input(f"Введите число жителей дома {i}: "))
    if i % 2 == 0:
        even = even + k
    else:
        odd = odd + k
if even > odd:
    print("Больше жителей проживает на стороне с четными номерами домов")
elif odd > even:
    print("Больше жителей проживает на стороне с нечетными номерами домов")
else:
    print("На обеих сторонах улицы проживает одинаковое число жителей")
