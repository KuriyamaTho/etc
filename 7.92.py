s1 = 0
s2 = 0
for i in range(1, 11):
    a = float(input(f"Первый спортсмен, баллы в виде {i}: "))
    s1 = s1 + a
for i in range(1, 11):
    b = float(input(f"Второй спортсмен, баллы в виде {i}: "))
    s2 = s2 + b
if s1 > s2:
    print("Лучший результат показал первый спортсмен")
elif s2 > s1:
    print("Лучший результат показал второй спортсмен")
else:
    print("Результаты спортсменов одинаковы")
