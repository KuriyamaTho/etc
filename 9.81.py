w1 = input("1) Введите первое слово: ")
w2 = input("1) Введите второе слово (слова разные): ")
i = 0
while i < len(w1) and i < len(w2) and w1[i] == w2[i]:
    i = i + 1
print("1) Совпадающих начальных букв:", i)

