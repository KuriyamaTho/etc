n = int(input("Введите натуральное число: "))

# а)
m = n
k = 0
while m > 0:
    if m % 10 == 3:
        k = k + 1
    m = m // 10
print("а) Количество цифр 3:", k)

# б)
last = n % 10
m = n
k = 0
while m > 0:
    if m % 10 == last:
        k = k + 1
    m = m // 10
print("б) Последняя цифра встречается раз:", k)

# в)
m = n
k = 0
while m > 0:
    if m % 10 % 2 == 0:
        k = k + 1
    m = m // 10
print("в) Количество четных цифр:", k)

# г)
m = n
s = 0
while m > 0:
    if m % 10 > 5:
        s = s + m % 10
    m = m // 10
print("г) Сумма цифр, больших пяти:", s)

# д)
m = n
p = 1
k = 0
while m > 0:
    if m % 10 > 7:
        p = p * (m % 10)
        k = k + 1
    m = m // 10
if k > 0:
    print("д) Произведение цифр, больших семи:", p)
else:
    print("д) В числе нет цифр, больших семи")

# е)
m = n
k = 0
while m > 0:
    if m % 10 == 0 or m % 10 == 5:
        k = k + 1
    m = m // 10
print("е) Цифры 0 и 5 встречаются всего раз:", k)
