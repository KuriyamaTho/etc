n = int(input("Введите количество студентов в группе: "))
k = 0
for i in range(1, n + 1):
    e1 = int(input(f"Студент {i}, оценка за первый экзамен: "))
    e2 = int(input(f"Студент {i}, оценка за второй экзамен: "))
    if e1 == 2 or e2 == 2:
        k = k + 1
print("Количество студентов, получивших двойку:", k)
